function seedState(){
  const locations = SEED_LOCATIONS.map((l, i) => ({row: i + 2, location: l.location, details: l.details}));
  const tenants = SEED_TENANTS.map((t, i) => ({
    row: i + 2,
    location: t.locName || SEED_LOCATIONS[t.loc].location,
    name: SEED_NAMES[t.name],
    dateIn: t.dateIn,
    dateOut: t.dateOut,
    deposit: t.deposit
  }));
  const data = SEED_DATA.map((r, i) => {
    const loc = SEED_LOCATIONS[r[1]].location;
    return {
      row: i + 2,
      date: r[0],
      location: loc,
      name: SEED_NAMES[r[2]],
      rent: r[3],
      water: r[4],
      elec: r[5],
      key: sheetSerial(parseISO(r[0])) + loc
    };
  });
  return {locations, tenants, data};
}
